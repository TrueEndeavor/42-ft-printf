#include "libft.h"

void	ft_putnbr_base_fd(int n, int fd, int base, int uppercase)
{
	long	nbr;

	nbr = n;
	if (nbr < 0)
	{
		ft_putchar_fd('-', fd);
		nbr = -nbr;
	}
	if (nbr >= base)
		ft_putnbr_base_fd(nbr / base, fd, base, uppercase);
	ft_putchar_fd(nbr % base + '0', fd);
}
